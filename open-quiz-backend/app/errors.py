"""Stable codes for the API errors a student can meet.

The frontend translates a response by its code, in every interface language;
the French message stays alongside it for whoever reads the API directly.
Every code needs a translation key in open-quiz-frontend/src/lib/errors.ts:
`pnpm test` fails otherwise.
"""

from enum import StrEnum


class ErrorCode(StrEnum):
    QUIZ_RATE_LIMITED = "QUIZ_RATE_LIMITED"
    QUIZ_JOIN_REJECTED = "QUIZ_JOIN_REJECTED"
    QUIZ_PARTICIPANT_TOKEN_MISSING = "QUIZ_PARTICIPANT_TOKEN_MISSING"  # noqa: S105 - an error code, not a secret.
    QUIZ_PARTICIPANT_TOKEN_INVALID = "QUIZ_PARTICIPANT_TOKEN_INVALID"  # noqa: S105 - an error code, not a secret.
    QUIZ_QUESTION_UNAVAILABLE = "QUIZ_QUESTION_UNAVAILABLE"
    QUIZ_NO_CURRENT_QUESTION = "QUIZ_NO_CURRENT_QUESTION"
    QUIZ_NOT_ACCEPTING_ANSWERS = "QUIZ_NOT_ACCEPTING_ANSWERS"
    QUIZ_STUDENT_REMOVED = "QUIZ_STUDENT_REMOVED"
    TRAINING_BLOCKED_BY_EXAM = "TRAINING_BLOCKED_BY_EXAM"
    ANSWER_WRITTEN_REQUIRED = "ANSWER_WRITTEN_REQUIRED"
    ANSWER_CHOICE_REQUIRED = "ANSWER_CHOICE_REQUIRED"
    ANSWER_MODE_MISMATCH = "ANSWER_MODE_MISMATCH"
    ANSWER_CHOICE_INVALID = "ANSWER_CHOICE_INVALID"
    QUIZ_ANSWERS_INCOMPLETE = "QUIZ_ANSWERS_INCOMPLETE"
    QUIZ_REVIEW_UNAVAILABLE = "QUIZ_REVIEW_UNAVAILABLE"
    QUIZ_PREVIOUS_QUESTION_LOCKED = "QUIZ_PREVIOUS_QUESTION_LOCKED"
    TRAINING_CLASS_REQUIRED = "TRAINING_CLASS_REQUIRED"
    TRAINING_NOT_FOUND = "TRAINING_NOT_FOUND"
    TRAINING_BANK_EMPTY = "TRAINING_BANK_EMPTY"
    MAKEUP_JOIN_REJECTED = "MAKEUP_JOIN_REJECTED"
    MAKEUP_SELECTION_CLOSED = "MAKEUP_SELECTION_CLOSED"
    MAKEUP_SELECTION_INVALID = "MAKEUP_SELECTION_INVALID"
    STUDENT_SESSION_INVALID = "STUDENT_SESSION_INVALID"


def api_error(code: ErrorCode, message: str) -> dict[str, str]:
    return {"code": code.value, "message": message}
